"""Generates the self-contained Ultralytics training script used for both Kaggle kernels and local runs."""
from __future__ import annotations

import json

TEMPLATE = r'''# Auto-generated by YOLOFlow Studio - do not edit by hand.
import glob
import json
import os
import shutil
import subprocess
import sys
import time
import zipfile

CONFIG = json.loads(r"""__CONFIG__""")


def log(msg):
    print(f"[yoloflow] {msg}", flush=True)


def ensure_ultralytics():
    try:
        import ultralytics  # noqa: F401
        log(f"ultralytics {ultralytics.__version__} already installed")
    except ImportError:
        spec = CONFIG.get("pip_spec") or "ultralytics"
        log(f"installing {spec}")
        subprocess.check_call([sys.executable, "-m", "pip", "install", "-q", spec])


def disable_integrations():
    os.environ["WANDB_MODE"] = "disabled"
    os.environ["WANDB_DISABLED"] = "true"
    from ultralytics import settings
    for key in ("wandb", "mlflow", "comet", "clearml", "dvc", "neptune", "raytune", "tensorboard"):
        try:
            settings.update({key: False})
        except Exception:
            pass


def locate_dataset():
    """Return the dataset root containing images/ and labels/."""
    if CONFIG.get("dataset_root"):
        return CONFIG["dataset_root"]
    search_root = CONFIG.get("search_root", "/kaggle/input")
    hits = glob.glob(os.path.join(search_root, "**", "data.yaml"), recursive=True)
    if not hits:
        zips = glob.glob(os.path.join(search_root, "**", "*.zip"), recursive=True)
        if not zips:
            raise SystemExit(f"No data.yaml or dataset zip found under {search_root}")
        out = os.path.join(CONFIG["work_dir"], "dataset")
        log(f"extracting {zips[0]} -> {out}")
        with zipfile.ZipFile(zips[0]) as zf:
            zf.extractall(out)
        hits = glob.glob(os.path.join(out, "**", "data.yaml"), recursive=True)
    root = os.path.dirname(hits[0])
    manifest = os.path.join(root, "manifest.json")
    if os.path.exists(manifest) and CONFIG.get("run_id"):
        with open(manifest) as f:
            got = json.load(f).get("run_id")
        if got != CONFIG["run_id"]:
            log(f"WARNING: dataset manifest run_id={got} differs from this run ({CONFIG['run_id']}); "
                "Kaggle may have attached an older dataset version.")
    return root


def write_data_yaml(root):
    def count(split):
        d = os.path.join(root, "images", split)
        return len(os.listdir(d)) if os.path.isdir(d) else 0

    n_train, n_val = count("train"), count("val")
    log(f"dataset: {n_train} train / {n_val} val images, {len(CONFIG['names'])} classes")
    if n_train == 0:
        raise SystemExit("Training split is empty - annotate some images first.")
    lines = [
        f"path: {json.dumps(root.replace(chr(92), '/'))}",
        "train: images/train",
        f"val: {'images/val' if n_val else 'images/train'}",
        f"nc: {len(CONFIG['names'])}",
        "names:",
    ]
    lines += [f"  {i}: {json.dumps(n)}" for i, n in enumerate(CONFIG["names"])]
    path = os.path.join(CONFIG["work_dir"], "data.yaml")
    os.makedirs(CONFIG["work_dir"], exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return path


def resolve_device():
    import torch
    want = str(CONFIG.get("device", "auto")).strip()
    if want in ("", "auto"):
        return 0 if torch.cuda.is_available() else "cpu"
    if want == "cpu" or not torch.cuda.is_available():
        if want != "cpu":
            log(f"CUDA not available - requested device {want}, falling back to CPU")
        return "cpu"
    ids = [int(x) for x in want.split(",") if x.strip().isdigit()]
    ids = [i for i in ids if i < torch.cuda.device_count()] or [0]
    return ids[0] if len(ids) == 1 else ids


def collect_artifacts(save_dir, best_onnx):
    out = CONFIG["artifact_dir"]
    os.makedirs(out, exist_ok=True)
    wanted = [os.path.join(save_dir, "weights", "best.pt"), os.path.join(save_dir, "weights", "last.pt"),
              os.path.join(save_dir, "results.csv"), os.path.join(save_dir, "args.yaml")]
    wanted += glob.glob(os.path.join(save_dir, "*.png")) + glob.glob(os.path.join(save_dir, "*.jpg"))
    if best_onnx:
        wanted.append(best_onnx)
    for p in wanted:
        if p and os.path.exists(p):
            shutil.copy2(p, os.path.join(out, os.path.basename(p)))
    log(f"artifacts copied to {out}")


def main():
    t0 = time.time()
    ensure_ultralytics()
    disable_integrations()
    from ultralytics import YOLO

    root = locate_dataset()
    data_yaml = write_data_yaml(root)
    device = resolve_device()
    log(f"model={CONFIG['model']} device={device}")

    model = YOLO(CONFIG["model"])
    train_args = dict(
        data=data_yaml,
        epochs=int(CONFIG["epochs"]),
        imgsz=int(CONFIG["imgsz"]),
        batch=CONFIG["batch"],
        optimizer=CONFIG["optimizer"],
        lr0=float(CONFIG["lr0"]),
        patience=int(CONFIG.get("patience", 100)),
        device=device,
        project=CONFIG["project_dir"],
        name="train",
        exist_ok=True,
        plots=True,
        verbose=True,
    )
    if CONFIG.get("workers") is not None:
        train_args["workers"] = int(CONFIG["workers"])
    if not CONFIG.get("pretrained", True):
        train_args["pretrained"] = False
    results = model.train(**train_args)

    save_dir = str(getattr(getattr(model, "trainer", None), "save_dir", os.path.join(CONFIG["project_dir"], "train")))
    best_pt = os.path.join(save_dir, "weights", "best.pt")
    metrics = {}
    try:
        metrics = {k: float(v) for k, v in (getattr(results, "results_dict", None) or {}).items()}
    except Exception as exc:
        log(f"could not read final metrics: {exc}")

    best_onnx = None
    if CONFIG.get("export_onnx", True) and os.path.exists(best_pt):
        try:
            log("exporting best.pt to ONNX")
            best_onnx = YOLO(best_pt).export(format="onnx", imgsz=int(CONFIG["imgsz"]))
        except Exception as exc:
            log(f"ONNX export failed: {exc}")

    collect_artifacts(save_dir, best_onnx)
    with open(os.path.join(CONFIG["artifact_dir"], "metrics.json"), "w") as f:
        json.dump({"metrics": metrics, "elapsed_seconds": round(time.time() - t0, 1),
                   "model": CONFIG["model"], "names": CONFIG["names"]}, f, indent=2)
    log("training finished")


if __name__ == "__main__":
    main()
'''


def render(config: dict) -> str:
    payload = json.dumps(config, indent=2)
    if '"""' in payload:
        raise ValueError("Config contains an unsupported character sequence.")
    return TEMPLATE.replace("__CONFIG__", payload)
